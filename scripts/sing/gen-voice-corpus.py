def synth(text, idx, timeout=200):
    body = json.dumps({'text': text, 'voice_id': VOICE,
                       'voice_settings': {'style': STYLE, 'speed': 1.0}}).encode('utf-8')
    req = urllib.request.Request(PROXY, data=body,
                                 headers={'content-type': 'application/json'})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def to_wav(mp3, wav):
    subprocess.run([FFMPEG, '-y', '-loglevel', 'error', '-i', mp3,
                    '-ar', '44100', '-ac', '1', wav], check=True)


def dur(p):
    r = subprocess.run([FFPROBE, '-v', 'error', '-show_entries', 'format=duration',
                        '-of', 'csv=p=0', p], capture_output=True, text=True)
    try:
        return float(r.stdout.strip())
    except Exception:
        return 0.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--pilot', action='store_true')
    ap.add_argument('--all', action='store_true')
    ap.add_argument('--start', type=int, default=0)
    args = ap.parse_args()

    os.makedirs(OUT_MP3, exist_ok=True)
    os.makedirs(OUT_WAV, exist_ok=True)

    items = SENTENCES[:10] if args.pilot else SENTENCES
    total_s = 0.0
    ok = 0
    fail = 0
    t0 = time.time()
    for i, text in enumerate(items, 1):
        idx = args.start + i
        mp3 = os.path.join(OUT_MP3, '%04d.mp3' % idx)
        wav = os.path.join(OUT_WAV, '%04d.wav' % idx)
        if os.path.exists(wav) and os.path.getsize(wav) > 1000:
            ok += 1
            continue
        try:
            data = synth(text, idx)
            open(mp3, 'wb').write(data)
            to_wav(mp3, wav)
            d = dur(wav)
            total_s += d
            ok += 1
            print('  [%3d/%3d] %.1fs  %s' % (i, len(items), d, text[:26]))
        except Exception as e:
            fail += 1
            print('  [%3d/%3d] ❌ %s  %s' % (i, len(items), str(e)[:60], text[:20]))
            time.sleep(2)

    print('')
    print('  成功 %d / 失败 %d' % (ok, fail))
    print('  本次新增音频 %.1f 秒（%.2f 分钟）' % (total_s, total_s / 60))
    print('  用时 %.1f 分钟' % ((time.time() - t0) / 60))
    print('  输出: %s' % OUT_WAV)


if __name__ == '__main__':
    main()
