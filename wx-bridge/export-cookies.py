"""
export-cookies.py —— 只导 cookies（不刷、不发任何东西，约 20 秒）

用途：让 yt-dlp 能下抖音（"静音刷 + 下载抽音轨"必须要有它）。
复用刷推荐流那个已登录的 profile，打开抖音首页 → 导出 Netscape cookies.txt → 关浏览器。

用法：python export-cookies.py
输出：data/_douyin/cookies.txt
"""
import asyncio, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROFILE = os.path.join(HERE, '..', 'data', 'douyin-profile')
COOKIE_FILE = os.path.join(HERE, '..', 'data', '_douyin', 'cookies.txt')


async def main():
    from playwright.async_api import async_playwright
    if not os.path.isdir(PROFILE):
        print('没有 douyin-profile（还没刷过？先跑一次 douyin-brush.py）')
        return 1
    async with async_playwright() as p:
        ctx = await p.chromium.launch_persistent_context(
            user_data_dir=PROFILE,
            channel='msedge',
            headless=False,                     # 有头（headless 会被弹验证）
            viewport={'width': 1280, 'height': 900},
            locale='zh-CN',
            args=['--disable-blink-features=AutomationControlled',
                  '--autoplay-policy=no-user-gesture-required',
                  '--mute-audio',               # 顺带静音，免得打开就出声
                  '--window-position=-32000,-32000',
                  '--window-size=1280,900'],
            ignore_default_args=['--enable-automation'],
        )
        try:
            pg = ctx.pages[0] if ctx.pages else await ctx.new_page()
            await pg.goto('https://www.douyin.com/', wait_until='domcontentloaded', timeout=90000)
            await pg.wait_for_timeout(3000)
            cookies = await ctx.cookies()
            rows = ['# Netscape HTTP Cookie File', '# generated by export-cookies.py']
            n = 0
            for c in cookies:
                dom = c.get('domain') or ''
                if 'douyin' not in dom and 'iesdouyin' not in dom:
                    continue
                exp = int(c.get('expires') or 0) or 2147483647
                flag = 'TRUE' if dom.startswith('.') else 'FALSE'
                secure = 'TRUE' if c.get('secure') else 'FALSE'
                prefix = '#HttpOnly_' if c.get('httpOnly') else ''
                rows.append('%s%s\t%s\t%s\t%s\t%d\t%s\t%s' % (
                    prefix, dom, flag, c.get('path') or '/', secure, exp,
                    c.get('name') or '', c.get('value') or ''))
                n += 1
            os.makedirs(os.path.dirname(COOKIE_FILE), exist_ok=True)
            with open(COOKIE_FILE, 'w', encoding='utf-8', newline='\n') as f:
                f.write('\n'.join(rows) + '\n')
            print('已导出 %d 条 douyin cookies → %s' % (n, COOKIE_FILE))
            return 0 if n else 2
        finally:
            await ctx.close()


sys.exit(asyncio.run(main()))
